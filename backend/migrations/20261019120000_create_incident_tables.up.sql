CREATE TABLE incident_types (
    id              smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            text UNIQUE,
    label           text,
    endangers_life  boolean
);

CREATE TABLE incidents (
    id                  uuid PRIMARY KEY,
    reporter_id         uuid REFERENCES users (id) ON DELETE SET NULL,
    type_id             smallint    NOT NULL REFERENCES incident_types (id),
    description         text        NOT NULL,
    status              text        DEFAULT 'reported',
    priority            text        DEFAULT 'normal',
    citizens_rescued    smallint    DEFAULT 0,
    street              text,
    postal_code         text,
    city                text,
    country             text,
    address_complement  text,
    latitude            numeric(9,6),
    longitude           numeric(9,6),
    occurred_at         timestamptz,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT incidents_status_check CHECK (status IN ('reported', 'in_progress', 'succeeded', 'failed')),
    CONSTRAINT incidents_priority_check CHECK (priority IN ('high', 'normal', 'low'))
);

CREATE INDEX incidents_status_priority_created_idx ON incidents (status, priority, created_at DESC);
CREATE INDEX incidents_location_duplicate_idx ON incidents (lower(city), postal_code, lower(street));

CREATE TABLE interventions (
    id               uuid PRIMARY KEY,
    incident_id      uuid        NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    status           text        DEFAULT 'in_progress',
    proposed_status  text,
    proposed_by      uuid        REFERENCES hero_profiles (user_id) ON DELETE SET NULL,
    decided_by       uuid        REFERENCES users (id) ON DELETE SET NULL,
    notes            text,
    started_at       timestamptz,
    ended_at         timestamptz,

    CONSTRAINT interventions_status_check CHECK (status IN ('in_progress', 'succeeded', 'failed')),
    CONSTRAINT interventions_proposed_status_check CHECK (proposed_status IS NULL OR proposed_status IN ('succeeded', 'failed'))
);

CREATE UNIQUE INDEX interventions_one_active_per_incident_idx
    ON interventions (incident_id) WHERE status = 'in_progress';

CREATE TABLE intervention_heroes (
    intervention_id    uuid        NOT NULL REFERENCES interventions (id) ON DELETE CASCADE,
    hero_id            uuid        NOT NULL REFERENCES hero_profiles (user_id),
    role               text,
    participation      text,
    invited_by         uuid        REFERENCES hero_profiles (user_id),
    outcome_validation text        DEFAULT 'pending',
    is_active          boolean,
    invited_at         timestamptz,
    joined_at          timestamptz,

    CONSTRAINT intervention_heroes_pk PRIMARY KEY (intervention_id, hero_id),
    CONSTRAINT intervention_heroes_role_check CHECK (role IN ('lead', 'member')),
    CONSTRAINT intervention_heroes_participation_check CHECK (participation IN ('invited', 'confirmed')),
    CONSTRAINT intervention_heroes_outcome_validation_check CHECK (outcome_validation IN ('pending', 'approved', 'rejected'))
);

CREATE UNIQUE INDEX intervention_heroes_one_active_intervention_idx
    ON intervention_heroes (hero_id) WHERE is_active;
CREATE UNIQUE INDEX intervention_heroes_one_lead_idx
    ON intervention_heroes (intervention_id) WHERE role = 'lead';

CREATE TABLE villains (
    id          uuid PRIMARY KEY,
    alias       text        NOT NULL UNIQUE,
    last_name   text,
    first_name  text,
    main_sector text,
    description text,
    created_by  uuid        REFERENCES users (id) ON DELETE SET NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE villain_specialties (
    villain_id uuid     NOT NULL REFERENCES villains (id) ON DELETE CASCADE,
    type_id    smallint NOT NULL REFERENCES incident_types (id),

    CONSTRAINT villain_specialties_pk PRIMARY KEY (villain_id, type_id)
);

CREATE TABLE incident_villains (
    incident_id uuid    NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    villain_id  uuid    NOT NULL REFERENCES villains (id),
    arrested    boolean NOT NULL DEFAULT false,

    CONSTRAINT incident_villains_pk PRIMARY KEY (incident_id, villain_id)
);
